from typing import Dict, Any, List

def generate_report_markdown(incident: Dict[str, Any], investigation: Dict[str, Any]) -> str:
    """Generate a markdown report for an incident."""
    
    md_lines = [
        "--------------------------------------------------",
        "## AI CYBERSECURITY INCIDENT INVESTIGATION REPORT",
        "--------------------------------------------------",
        "",
        f"**Incident ID:** {incident.get('id', 'N/A')}",
        f"**Date:** {incident.get('created_at', 'N/A')}",
        f"**Severity:** {incident.get('severity', 'N/A')}",
        f"**Status:** {incident.get('status', 'N/A')}",
        "",
        "### 1. Executive Summary",
        investigation.get('summary', 'No summary available.'),
        "",
        "### 2. Incident Overview",
        f"- **Type:** {incident.get('incident_type', 'N/A')}",
        f"- **Source IP:** {incident.get('source_ip', 'N/A')}",
        f"- **Affected User:** {incident.get('affected_user', 'N/A')}",
        f"- **Confidence:** {float(incident.get('confidence', 0))*100:.1f}%",
        "",
        "### 3. AI Analysis",
        investigation.get('ai_analysis', 'No AI analysis available.'),
        "",
        "### 4. Recommended Defensive Actions",
        investigation.get('recommended_actions', 'No recommendations available.'),
        "",
        "### 5. Detected Suspicious Patterns",
    ]
    
    # Add detections
    detections = incident.get('detections', [])
    if detections:
        for d in detections:
            md_lines.append(f"- **{d.get('rule_name')}**: {d.get('explanation')}")
    else:
        md_lines.append("No specific patterns mapped.")
        
    md_lines.append("")
    md_lines.append("--------------------------------------------------")
    md_lines.append("*Generated by AI Cybersecurity Incident Investigator*")
    
    return "\n".join(md_lines)
